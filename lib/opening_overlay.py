"""Cluster-conditional opening overlay.

At step 0, classify the board into one of 4 clusters via the KMeans
model fit on top-10 win replays (`audit/2026-05-14-opening-overlay-
model.json`). For steps 0-30, the overlay proposes launches matching
the cluster's empirical opening template:

| cluster | first launch | launches in 30 | target dist | target prod | launches / turn |
|---|---|---|---|---|---|
| 0 (sparse-static-rich)        | t=5  | 4   | 44 | 3.5 | 0.73 |
| 1 (wide-mixed; blitz regime) | t=4  | 7.5 | 45 | 3.0 | 1.03 |
| 2 (close-quarters)           | t=1.5| 5   | 44 | 2.6 | 0.59 |
| 3 (close-quarters-orbital)   | t=4  | 6   | 37 | 3.3 | 0.69 |

After step 30 the overlay returns `None`, ceding control to the
caller (v7 search). The overlay is hand-off-clean: any state it
caches lives on the agent-side closure, never inside lib state.

The model JSON is embedded as a Python dict at module-load time so
the agent can be bundled by `scripts/bundle_agent.py` without an
external file dependency.
"""

